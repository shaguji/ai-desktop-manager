  'use strict';

  const WEEKDAYS = ['星期日', '星期一', '星期二', '星期三', '星期四', '星期五', '星期六'];
  const MONTH_CN = ['一月', '二月', '三月', '四月', '五月', '六月', '七月', '八月', '九月', '十月', '十一月', '十二月'];

  const pad = (n) => String(n).padStart(2, '0');
  const fmt = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;

  function isoWeek(d) {
    const t = new Date(d.getFullYear(), d.getMonth(), d.getDate());
    t.setDate(t.getDate() + 3 - ((t.getDay() + 6) % 7));
    const week1 = new Date(t.getFullYear(), 0, 4);
    return 1 + Math.round(((t - week1) / 86400000 - 3 + ((week1.getDay() + 6) % 7)) / 7);
  }

  function buildVars(now) {
    const d = now ? new Date(now) : new Date();
    const y = d.getFullYear();
    const m = d.getMonth() + 1;

    // 本周一 ~ 本周日
    const monday = new Date(y, d.getMonth(), d.getDate());
    monday.setDate(monday.getDate() - ((monday.getDay() + 6) % 7));
    const sunday = new Date(monday);
    sunday.setDate(sunday.getDate() + 6);
    const lastMonday = new Date(monday);
    lastMonday.setDate(lastMonday.getDate() - 7);
    const lastSunday = new Date(monday);
    lastSunday.setDate(lastSunday.getDate() - 1);

    const lastDay = new Date(y, m, 0).getDate();
    const quarter = Math.floor((m - 1) / 3) + 1;
    const lastMonth = m === 1 ? 12 : m - 1;
    const lastMonthYear = m === 1 ? y - 1 : y;

    return {
      author: '我',
      date: fmt(d),
      date_cn: `${y}年${m}月${d.getDate()}日`,
      date_short: `${m}月${d.getDate()}日`,
      weekday: WEEKDAYS[d.getDay()],
      year: String(y),
      next_year: String(y + 1),
      last_year: String(y - 1),
      year_start: `${y}-01-01`,
      year_end: `${y}-12-31`,
      quarter: `Q${quarter}`,
      month: pad(m),
      month_cn: MONTH_CN[d.getMonth()],
      month_cn_full: `${y} 年 ${m} 月`,
      day: pad(d.getDate()),
      week: String(isoWeek(d)),
      time: `${pad(d.getHours())}:${pad(d.getMinutes())}`,
      datetime: `${fmt(d)} ${pad(d.getHours())}:${pad(d.getMinutes())}`,
      week_start: fmt(monday),
      week_end: fmt(sunday),
      week_range: `${fmt(monday)} ~ ${fmt(sunday)}`,
      last_week_range: `${fmt(lastMonday)} ~ ${fmt(lastSunday)}`,
      month_range: `${y}-${pad(m)}-01 ~ ${y}-${pad(m)}-${lastDay}`,
      quarter_range: `${y}-${pad((quarter - 1) * 3 + 1)}-01 ~ ${y}-${pad(quarter * 3)}-${new Date(y, quarter * 3, 0).getDate()}`,
      last_month: `${lastMonthYear} 年 ${lastMonth} 月`,
      last_day: String(lastDay)
    };
  }

  function render(text, vars) {
    const v = vars || buildVars();
    return String(text || '').replace(/\{\{\s*([a-z_]+)\s*\}\}/gi, (m, key) => {
      const k = key.toLowerCase();
      return Object.prototype.hasOwnProperty.call(v, k) ? v[k] : m;
    });
  }

